import { useState, useEffect, useRef } from 'react'
import {
  generateAiSuggestionFromText,
  classifyDiscrepancyTags,
  fetchJobStatus,
  scanBarcodeOrLabel,
  describeEvidenceWithAi
} from '@/services/suggestionService'

/**
 * Downscales & converts a File or Blob or DataURL image into a compact Base64 string + mimeType
 * so label scanning is fast and stays well within request size limits.
 */
async function fileOrDataUrlToBase64(input) {
  if (typeof input === 'string' && input.startsWith('data:')) {
    const [meta, base64] = input.split(',')
    const mimeMatch = meta.match(/data:([^;]+);/)
    return { base64: base64 || '', mimeType: mimeMatch ? mimeMatch[1] : 'image/jpeg' }
  }

  return new Promise((resolve, reject) => {
    const reader = new FileReader()
    reader.onload = () => {
      const dataUrl = String(reader.result || '')
      const img = new Image()
      img.onload = () => {
        const maxDim = 1280
        let { width, height } = img
        if (width > maxDim || height > maxDim) {
          if (width > height) {
            height = Math.round((height * maxDim) / width)
            width = maxDim
          } else {
            width = Math.round((width * maxDim) / height)
            height = maxDim
          }
        }
        const canvas = document.createElement('canvas')
        canvas.width = width
        canvas.height = height
        const ctx = canvas.getContext('2d')
        ctx.drawImage(img, 0, 0, width, height)
        const compressedUrl = canvas.toDataURL('image/jpeg', 0.85)
        const [, base64] = compressedUrl.split(',')
        resolve({ base64: base64 || '', mimeType: 'image/jpeg' })
      }
      img.onerror = () => {
        const [meta, base64] = dataUrl.split(',')
        const mimeMatch = meta.match(/data:([^;]+);/)
        resolve({ base64: base64 || '', mimeType: mimeMatch ? mimeMatch[1] : 'image/jpeg' })
      }
      img.src = dataUrl
    }
    reader.onerror = (err) => reject(err)
    reader.readAsDataURL(input)
  })
}

export function useQDDRForm() {
  const initialState = {
    location: '',
    date: '',
    time: '',
    trucker_broker: '',
    plate_number: '',
    container_number: '',
    po_reference: '',
    drwb_number: '',
    brand_supplier: '',
    material_description: '',
    material_code: '',
    batch_code_su_number: '',
    holes_punctures: false,
    deformed_torn: false,
    open_carton: false,
    crushed_dented: false,
    wet_leaked: false,
    stain_graffiti: false,
    bulging: false,
    improper_stretch_wrapping: false,
    wrong_no_batchcode: false,
    opened_seal: false,
    no_label_broken_label: false,
    short_pack: false,
    excess_shipment: false,
    documentation_error: false,
    picking_discrepancy: false,
    others: '',
    qty: '',
    reason_of_discrepancy: '',
    corrective_action: '',
    preventive_action: '',
    approved_by: '',
    noted_by: '',
    leader: '',
    evidence_urls: []
  }

  const [form, setForm] = useState(initialState)
  const [error, setError] = useState(null)
  const [isSubmitting, setIsSubmitting] = useState(false)
  const [suggesting, setSuggesting] = useState(false)
  const [generatingReason, setGeneratingReason] = useState(false)
  const [scanningLabel, setScanningLabel] = useState(false)
  const [scanMessage, setScanMessage] = useState(null)
  const [evidenceItems, setEvidenceItems] = useState([])
  const [evidenceError, setEvidenceError] = useState(null)
  const lastClassifiedReasonRef = useRef('')
  const autoGeneratedReasonKeyRef = useRef('')

  useEffect(() => {
    const desc = (form.reason_of_discrepancy || '').trim()
    if (desc.length < 15 || desc === lastClassifiedReasonRef.current) return

    const timer = setTimeout(async () => {
      try {
        lastClassifiedReasonRef.current = desc
        const data = await classifyDiscrepancyTags({ description: desc, type: 'QDDR' })
        if (Array.isArray(data?.tags) && data.tags.length > 0) {
          setForm(prev => {
            const updates = {}
            data.tags.forEach(t => {
              if (t in initialState) updates[t] = true
            })
            return { ...prev, ...updates }
          })
        }
      } catch (err) {
        console.warn('Auto QDDR tag classification failed', err)
      }
    }, 800)

    return () => clearTimeout(timer)
  }, [form.reason_of_discrepancy])

  const handleChange = (key, value) => {
    setForm(prev => ({ ...prev, [key]: value }))
    if (error) setError('')
  }

  const resetForm = () => {
    setForm(initialState)
    setError(null)
    setScanMessage(null)
    setEvidenceError(null)
    autoGeneratedReasonKeyRef.current = ''
    setEvidenceItems(prev => {
      prev.forEach(item => {
        if (!item.isExisting && item.url?.startsWith('blob:')) {
          URL.revokeObjectURL(item.url)
        }
      })
      return []
    })
  }

  const initForm = (existingQddr) => {
    const existingUrls = Array.isArray(existingQddr.evidence_urls) ? existingQddr.evidence_urls : []
    setForm({
      ...initialState,
      ...existingQddr,
      location: existingQddr.location || '',
      date: existingQddr.date ? existingQddr.date.split('T')[0] : '',
      time: existingQddr.time || '',
      trucker_broker: existingQddr.trucker_broker || '',
      plate_number: existingQddr.plate_number || '',
      container_number: existingQddr.container_number || '',
      po_reference: existingQddr.po_reference || '',
      drwb_number: existingQddr.drwb_number || '',
      brand_supplier: existingQddr.brand_supplier || '',
      material_description: existingQddr.material_description || '',
      material_code: existingQddr.material_code || '',
      batch_code_su_number: existingQddr.batch_code_su_number || '',
      holes_punctures: Boolean(existingQddr.holes_punctures),
      deformed_torn: Boolean(existingQddr.deformed_torn),
      open_carton: Boolean(existingQddr.open_carton),
      crushed_dented: Boolean(existingQddr.crushed_dented),
      wet_leaked: Boolean(existingQddr.wet_leaked),
      stain_graffiti: Boolean(existingQddr.stain_graffiti),
      bulging: Boolean(existingQddr.bulging),
      improper_stretch_wrapping: Boolean(existingQddr.improper_stretch_wrapping),
      wrong_no_batchcode: Boolean(existingQddr.wrong_no_batchcode),
      opened_seal: Boolean(existingQddr.opened_seal),
      no_label_broken_label: Boolean(existingQddr.no_label_broken_label),
      short_pack: Boolean(existingQddr.short_pack),
      excess_shipment: Boolean(existingQddr.excess_shipment),
      documentation_error: Boolean(existingQddr.documentation_error),
      picking_discrepancy: Boolean(existingQddr.picking_discrepancy),
      others: existingQddr.others || '',
      qty: existingQddr.qty || '',
      reason_of_discrepancy: existingQddr.reason_of_discrepancy || '',
      corrective_action: existingQddr.corrective_action || '',
      preventive_action: existingQddr.preventive_action || '',
      approved_by: existingQddr.approved_by || '',
      noted_by: existingQddr.noted_by || '',
      leader: existingQddr.leader || '',
      evidence_urls: existingUrls
    })
    setEvidenceItems(
      existingUrls.map((url, idx) => {
        const lower = String(url || '').toLowerCase()
        const isImg = /\.(jpg|jpeg|png|webp|gif)(\?|$)/i.test(lower) || lower.startsWith('data:image/')
        const name = url.startsWith('data:')
          ? `Attachment ${idx + 1}`
          : decodeURIComponent(url.split('/').pop()?.split('?')[0] || `Attachment ${idx + 1}`)
        return {
          file: null,
          url,
          name,
          type: isImg ? 'image/jpeg' : 'application/octet-stream',
          isExisting: true
        }
      })
    )
    setEvidenceError(null)
    setError(null)
    autoGeneratedReasonKeyRef.current = ''
  }

  const handleEvidenceFiles = (selectedFiles = []) => {
    setEvidenceError(null)
    const incoming = Array.from(selectedFiles || [])
    if (incoming.length === 0) return

    const maxFiles = 3
    if (evidenceItems.length + incoming.length > maxFiles) {
      setEvidenceError(`You can upload up to ${maxFiles} evidence files.`)
      return
    }

    const allowedExtensions = /\.(jpg|jpeg|png|webp|gif|pdf|doc|docx)$/i
    const maxBytes = 10 * 1024 * 1024 // 10 MB

    const validNewItems = []
    for (const file of incoming) {
      if (!allowedExtensions.test(file.name) && !file.type.startsWith('image/')) {
        setEvidenceError('Unsupported file format. Please upload an image (JPG, PNG, WEBP) or document (PDF, DOC, DOCX).')
        return
      }
      if (file.size > maxBytes) {
        setEvidenceError(`File "${file.name}" exceeds the 10 MB size limit.`)
        return
      }
      validNewItems.push({
        file,
        url: URL.createObjectURL(file),
        name: file.name,
        type: file.type || (/\.(jpg|jpeg|png|webp|gif)$/i.test(file.name) ? 'image/jpeg' : 'application/octet-stream'),
        isExisting: false
      })
    }

    setEvidenceItems(prev => [...prev, ...validNewItems])
  }

  const removeEvidenceFile = (index) => {
    setEvidenceError(null)
    setEvidenceItems(prev => {
      const target = prev[index]
      if (target && !target.isExisting && target.url?.startsWith('blob:')) {
        URL.revokeObjectURL(target.url)
      }
      const next = prev.filter((_, i) => i !== index)
      const remainingExistingUrls = next.filter(i => i.isExisting).map(i => i.url)
      setForm(f => ({ ...f, evidence_urls: remainingExistingUrls }))
      return next
    })
  }

  const checkboxFields = [
    { key: 'holes_punctures', label: 'HOLES & PUNCTURES' },
    { key: 'deformed_torn', label: 'DEFORMED OR TORN' },
    { key: 'open_carton', label: 'OPEN CARTON' },
    { key: 'crushed_dented', label: 'CRUSHED OR DENTED' },
    { key: 'wet_leaked', label: 'WET OR LEAKED' },
    { key: 'stain_graffiti', label: 'STAIN OR GRAFFITI' },
    { key: 'bulging', label: 'BULGING' },
    { key: 'improper_stretch_wrapping', label: 'IMPROPER STRETCH WRAPPING' },
    { key: 'wrong_no_batchcode', label: 'WRONG/NO BATCHCODE' },
    { key: 'opened_seal', label: 'OPENED SEAL' },
    { key: 'no_label_broken_label', label: 'NO LABEL/BROKEN LABEL' },
    { key: 'short_pack', label: 'SHORT PACK' },
    { key: 'excess_shipment', label: 'EXCESS SHIPMENT' },
    { key: 'documentation_error', label: 'DOCUMENTATION ERROR' },
    { key: 'picking_discrepancy', label: 'PICKING DISCREPANCY' }
  ]

  const getCheckedDiscrepancyLabels = () =>
    checkboxFields
      .filter(f => form[f.key])
      .map(f => f.label)
      .join(', ')

  const generateReasonFromEvidence = async ({ silent = false } = {}) => {
    const missing = []
    if (!String(form.location || '').trim()) missing.push('Location')
    if (!String(form.material_description || '').trim()) missing.push('Material Description')
    if (!String(form.material_code || '').trim()) missing.push('Material Code')
    if (!String(form.batch_code_su_number || '').trim()) missing.push('Batch Code / ISU No')
    if (form.qty === '' || form.qty === null || form.qty === undefined || Number(form.qty) < 0) {
      missing.push('Quantity')
    }

    if (missing.length > 0) {
      if (!silent) {
        setError(`Please fill in required fields first to generate Reason of Discrepancy: ${missing.join(', ')}.`)
      }
      return null
    }

    const firstImageItem = (evidenceItems || []).find(item => {
      const isImgMime = String(item.type || '').startsWith('image/')
      const isImgExt = /\.(jpg|jpeg|png|webp|gif)(\?|$)/i.test(String(item.name || item.url || ''))
      const isDataUrl = String(item.url || '').startsWith('data:image/')
      return (isImgMime || isImgExt || isDataUrl) && (item.file || isDataUrl)
    })

    setGeneratingReason(true)
    if (!silent) setError(null)

    try {
      let imageBase64 = ''
      let mimeType = 'image/jpeg'

      if (firstImageItem) {
        const source = firstImageItem.file || firstImageItem.url
        const converted = await fileOrDataUrlToBase64(source)
        imageBase64 = converted.base64
        mimeType = converted.mimeType
      }

      const checkedTypes = getCheckedDiscrepancyLabels()

      const res = await describeEvidenceWithAi({
        reportType: 'QDDR',
        imageBase64,
        mimeType,
        location: form.location,
        materialDescription: form.material_description,
        materialCode: form.material_code,
        batchNumber: form.batch_code_su_number,
        qty: form.qty,
        discrepancyTypes: checkedTypes
      })

      if (res?.description) {
        lastClassifiedReasonRef.current = res.description.trim()
        setForm(prev => {
          const updates = { reason_of_discrepancy: res.description }
          if (Array.isArray(res.tags)) {
            res.tags.forEach(t => {
              if (t in initialState) updates[t] = true
            })
          }
          return { ...prev, ...updates }
        })
      }
      return res
    } catch (err) {
      console.error('Reason generation error:', err)
      if (!silent) {
        setError('Could not auto-generate Reason of Discrepancy. Please try again.')
      }
      return null
    } finally {
      setGeneratingReason(false)
    }
  }

  useEffect(() => {
    const hasAllRequired =
      Boolean(String(form.location || '').trim()) &&
      Boolean(String(form.material_description || '').trim()) &&
      Boolean(String(form.material_code || '').trim()) &&
      Boolean(String(form.batch_code_su_number || '').trim()) &&
      form.qty !== '' &&
      form.qty !== null &&
      form.qty !== undefined &&
      Number(form.qty) >= 0

    const firstImageItem = (evidenceItems || []).find(item => {
      const isImgMime = String(item.type || '').startsWith('image/')
      const isImgExt = /\.(jpg|jpeg|png|webp|gif)(\?|$)/i.test(String(item.name || item.url || ''))
      return isImgMime || isImgExt
    })

    if (!hasAllRequired || !firstImageItem || String(form.reason_of_discrepancy || '').trim() || generatingReason) {
      return
    }

    const triggerKey = `${form.location}|${form.material_code}|${form.batch_code_su_number}|${form.qty}|${firstImageItem.name || firstImageItem.url}`
    if (autoGeneratedReasonKeyRef.current === triggerKey) return
    autoGeneratedReasonKeyRef.current = triggerKey

    generateReasonFromEvidence({ silent: true })
  }, [
    form.location,
    form.material_description,
    form.material_code,
    form.batch_code_su_number,
    form.qty,
    form.reason_of_discrepancy,
    evidenceItems,
    generatingReason
  ])

  const suggestActions = async () => {
    if (!form.material_description?.trim() && !form.reason_of_discrepancy?.trim()) {
      setError('Please fill in Material Description and Reason of Discrepancy first.')
      return
    }

    setSuggesting(true)
    setError(null)

    const checkedTypes = getCheckedDiscrepancyLabels()

    const fullDescription = `Material: ${form.material_description || ''}. Discrepancy Type: ${checkedTypes || 'None'}. Reason: ${form.reason_of_discrepancy || ''}.`

    try {
      const result = await generateAiSuggestionFromText({
        description: fullDescription,
        issueType: checkedTypes || 'quality',
        deptName: form.location || 'N/A',
        reportType: 'QDDR'
      })

      let res = result
      if (result?.jobId) {
        res = await new Promise((resolve, reject) => {
          const maxRetries = 20
          let retries = 0
          const interval = setInterval(async () => {
            try {
              const status = await fetchJobStatus(result.jobId, result.queue)
              if (status.state === 'completed') {
                clearInterval(interval)
                resolve(status.output)
              } else if (status.state === 'failed' || status.state === 'cancelled') {
                clearInterval(interval)
                reject(new Error('Background job failed'))
              }
              if (++retries >= maxRetries) {
                clearInterval(interval)
                reject(new Error('Background job timeout'))
              }
            } catch (e) {
              // ignore transient network errors during polling
            }
          }, 3000)
        })
      }

      if (res) {
        setForm(prev => ({
          ...prev,
          corrective_action: res.suggestion || prev.corrective_action,
          preventive_action: res.preventive_suggestion || prev.preventive_action
        }))
      }
    } catch (err) {
      console.error('CBR suggestion error:', err)
      setError('We could not generate suggestions. Please try again later.')
    } finally {
      setSuggesting(false)
    }
  }

  const validate = () => {
    if (!String(form.location || '').trim()) {
      setError('Location is required.')
      return false
    }
    if (!String(form.material_description || '').trim()) {
      setError('Material Description is required.')
      return false
    }
    if (!String(form.material_code || '').trim()) {
      setError('Material Code is required.')
      return false
    }
    if (!String(form.batch_code_su_number || '').trim()) {
      setError('Batch Code / ISU No is required.')
      return false
    }
    if (form.qty === '' || form.qty === null || form.qty === undefined || Number(form.qty) < 0) {
      setError('Quantity is required.')
      return false
    }
    setError(null)
    return true
  }

  const handleScanLabel = async ({ imageFileOrDataUrl = null, rawBarcode = '' } = {}) => {
    if (!imageFileOrDataUrl && !rawBarcode) return null

    setScanningLabel(true)
    setError(null)
    setScanMessage(null)

    try {
      let imageBase64 = ''
      let mimeType = 'image/jpeg'

      if (imageFileOrDataUrl) {
        const converted = await fileOrDataUrlToBase64(imageFileOrDataUrl)
        imageBase64 = converted.base64
        mimeType = converted.mimeType
      }

      const result = await scanBarcodeOrLabel({
        imageBase64,
        mimeType,
        rawBarcode,
      })

      if (result) {
        const filledFields = []
        setForm(prev => {
          const next = { ...prev }
          if (result.material_code) {
            next.material_code = result.material_code
            filledFields.push('Item Code')
          }
          if (result.material_description) {
            let desc = result.material_description
            if (result.expiry_date && !desc.toLowerCase().includes(String(result.expiry_date).toLowerCase())) {
              desc = `${desc} (Exp: ${result.expiry_date})`
            }
            next.material_description = desc
            filledFields.push(result.expiry_date ? 'Item Description + Expiry Date' : 'Item Description')
          } else if (result.expiry_date) {
            next.material_description = prev.material_description
              ? `${prev.material_description} (Exp: ${result.expiry_date})`
              : `Exp: ${result.expiry_date}`
            filledFields.push('Expiry Date')
          }
          if (result.batch_code_su_number) {
            next.batch_code_su_number = result.batch_code_su_number
            filledFields.push('Batch Code')
          }
          return next
        })

        if (filledFields.length > 0) {
          setScanMessage(`Auto-filled: ${filledFields.join(', ')}`)
        } else {
          setError('Could not detect label fields from the barcode/image. Please try a clearer image.')
        }
      }
      return result
    } catch (err) {
      console.error('Label scan error:', err)
      setError('Failed to scan barcode/label image. Please try again.')
      return null
    } finally {
      setScanningLabel(false)
    }
  }

  return {
    form,
    setForm,
    handleChange,
    resetForm,
    initForm,
    error,
    setError,
    validate,
    isSubmitting,
    setIsSubmitting,
    suggesting,
    suggestActions,
    generatingReason,
    generateReasonFromEvidence,
    scanningLabel,
    scanMessage,
    setScanMessage,
    handleScanLabel,
    evidenceItems,
    evidenceError,
    handleEvidenceFiles,
    removeEvidenceFile,
    fileOrDataUrlToBase64
  }
}
