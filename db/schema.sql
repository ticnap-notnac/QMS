CREATE OR REPLACE FUNCTION public.current_user_has_right(required_right text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT public.is_current_user_admin() OR EXISTS (
    SELECT 1
    FROM public.users u
    INNER JOIN public.roles r ON r.id = u.role_id
    WHERE u.auth_id = auth.uid()
      AND coalesce(u.status, 'ACTIVE')::text <> 'DEACTIVATED'
      AND r.permissions IS NOT NULL
      AND jsonb_typeof(r.permissions -> 'rights') = 'array'
      AND (r.permissions -> 'rights') ? required_right
  );
$$;

CREATE OR REPLACE FUNCTION public.next_report_reference(
  p_type text,
  p_year integer DEFAULT NULL
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_type text := upper(trim(coalesce(p_type, '')));
  v_year integer := coalesce(p_year, EXTRACT(YEAR FROM CURRENT_DATE)::integer);
  v_next_seq integer;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('next_report_reference_' || v_type));

  IF v_type = 'CAR' THEN
    SELECT COALESCE(
      MAX(CAST(substring(reference_no FROM '^CAR-([0-9]+)$') AS integer)),
      0
    ) + 1
    INTO v_next_seq
    FROM public.car_reports
    WHERE reference_no ~ '^CAR-[0-9]+$';

    RETURN 'CAR-' || lpad(v_next_seq::text, 3, '0');

  ELSIF v_type = 'QDDR' THEN
    SELECT COALESCE(
      MAX(CAST(substring(reference_no FROM '^QDDR-([0-9]+)$') AS integer)),
      0
    ) + 1
    INTO v_next_seq
    FROM public.qddr_reports
    WHERE reference_no ~ '^QDDR-[0-9]+$';

    RETURN 'QDDR-' || lpad(v_next_seq::text, 3, '0');

  ELSE
    RAISE EXCEPTION 'Unsupported report type for reference generation: %. Only CAR and QDDR are supported.', p_type;
  END IF;
END;
$$;

-- Vector search functions for Case Repositories
CREATE OR REPLACE FUNCTION public.match_car_cases(
  query_embedding vector(768),
  match_threshold float DEFAULT 0.0,
  match_count int DEFAULT 10
)
RETURNS TABLE (
  id bigint,
  car_id bigint,
  reference_no varchar,
  details_of_nonconformance text,
  root_cause_analysis text,
  corrective_action text,
  preventive_action text,
  issue_category varchar,
  requesting_department varchar,
  responsible_department varchar,
  product_material_name varchar,
  effectiveness_score numeric,
  similarity float
)
LANGUAGE sql STABLE
AS $$
  SELECT
    c.id,
    c.car_id,
    c.reference_no,
    c.details_of_nonconformance,
    c.root_cause_analysis,
    c.corrective_action,
    c.preventive_action,
    c.issue_category,
    c.requesting_department,
    c.responsible_department,
    c.product_material_name,
    c.effectiveness_score,
    1 - (c.embedding <=> query_embedding) AS similarity
  FROM public.car_case_repository c
  WHERE c.embedding IS NOT NULL
    AND 1 - (c.embedding <=> query_embedding) >= match_threshold
  ORDER BY c.embedding <=> query_embedding
  LIMIT match_count;
$$;

