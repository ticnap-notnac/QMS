-- =============================================================================
-- Migration 036: Create `report_ratings` Table for Multi-User Closed Report Rating
-- =============================================================================
-- 1. Creates `public.report_ratings` for storing 1-5 star ratings per user per closed CAR/QDDR.
-- 2. Adds `average_rating` and `ratings_count` summary columns to `car_reports` and `qddr_reports`.
-- 3. Configures RLS policies so authenticated users can read ratings and service_role can manage all.
-- 4. Seeds existing closed CAR verification ratings into `report_ratings` and syncs `car_case_repository`.

BEGIN;

-- 1. Create `public.report_ratings` table
CREATE TABLE IF NOT EXISTS public.report_ratings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_type varchar(10) NOT NULL CHECK (report_type IN ('CAR', 'QDDR')),
  report_id bigint NOT NULL,
  user_auth_id uuid NOT NULL,
  rating int2 NOT NULL CHECK (rating BETWEEN 1 AND 5),
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  CONSTRAINT uq_report_ratings_user UNIQUE (report_type, report_id, user_auth_id)
);

CREATE INDEX IF NOT EXISTS idx_report_ratings_target
  ON public.report_ratings (report_type, report_id);

CREATE INDEX IF NOT EXISTS idx_report_ratings_user
  ON public.report_ratings (user_auth_id);

-- 2. Add summary columns to `car_reports` and `qddr_reports`
ALTER TABLE public.car_reports
  ADD COLUMN IF NOT EXISTS average_rating numeric(3,2) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS ratings_count int4 DEFAULT 0;

ALTER TABLE public.qddr_reports
  ADD COLUMN IF NOT EXISTS average_rating numeric(3,2) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS ratings_count int4 DEFAULT 0;

-- 3. Enable Row Level Security (RLS) on `report_ratings`
ALTER TABLE public.report_ratings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow authenticated select on report_ratings" ON public.report_ratings;
CREATE POLICY "Allow authenticated select on report_ratings"
  ON public.report_ratings FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "Allow authenticated insert own report_ratings" ON public.report_ratings;
CREATE POLICY "Allow authenticated insert own report_ratings"
  ON public.report_ratings FOR INSERT TO authenticated WITH CHECK (auth.uid() = user_auth_id);

DROP POLICY IF EXISTS "Allow authenticated update own report_ratings" ON public.report_ratings;
CREATE POLICY "Allow authenticated update own report_ratings"
  ON public.report_ratings FOR UPDATE TO authenticated USING (auth.uid() = user_auth_id) WITH CHECK (auth.uid() = user_auth_id);

DROP POLICY IF EXISTS "Allow all actions for service role on report_ratings" ON public.report_ratings;
CREATE POLICY "Allow all actions for service role on report_ratings"
  ON public.report_ratings FOR ALL TO service_role USING (true) WITH CHECK (true);

COMMIT;
