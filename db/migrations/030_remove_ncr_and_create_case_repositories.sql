-- =============================================================================
-- Step 3: Create Vector Search RPC Functions (768 Dimensions)
-- =============================================================================
CREATE OR REPLACE FUNCTION public.match_car_cases(
  query_embedding vector(768),
  match_threshold float DEFAULT 0.0,
  match_count int DEFAULT 10
)
RETURNS TABLE (
  id bigint,
  car_id bigint,
  reference_no varchar,
  details_of_nonconformance text,
  root_cause_analysis text,
  corrective_action text,
  preventive_action text,
  issue_category varchar,
  requesting_department varchar,
  responsible_department varchar,
  product_material_name varchar,
  effectiveness_score numeric,
  similarity float
)
LANGUAGE sql STABLE
AS $$
  SELECT
    c.id,
    c.car_id,
    c.reference_no,
    c.details_of_nonconformance,
    c.root_cause_analysis,
    c.corrective_action,
    c.preventive_action,
    c.issue_category,
    c.requesting_department,
    c.responsible_department,
    c.product_material_name,
    c.effectiveness_score,
    1 - (c.embedding <=> query_embedding) AS similarity
  FROM public.car_case_repository c
  WHERE c.embedding IS NOT NULL
    AND 1 - (c.embedding <=> query_embedding) >= match_threshold
  ORDER BY c.embedding <=> query_embedding
  LIMIT match_count;
$$;

CREATE OR REPLACE FUNCTION public.match_qddr_cases(
  query_embedding vector(768),
  match_threshold float DEFAULT 0.0,
  match_count int DEFAULT 10
)
RETURNS TABLE (
  id bigint,
  qddr_id bigint,
  reference_no varchar,
  reason_of_discrepancy text,
  material_description text,
  corrective_action text,
  preventive_action text,
  disposal_approved boolean,
  effectiveness_score numeric,
  similarity float
)
LANGUAGE sql STABLE
AS $$
  SELECT
    q.id,
    q.qddr_id,
    q.reference_no,
    q.reason_of_discrepancy,
    q.material_description,
    q.corrective_action,
    q.preventive_action,
    q.disposal_approved,
    q.effectiveness_score,
    1 - (q.embedding <=> query_embedding) AS similarity
  FROM public.qddr_case_repository q
  WHERE q.embedding IS NOT NULL
    AND 1 - (q.embedding <=> query_embedding) >= match_threshold
  ORDER BY q.embedding <=> query_embedding
  LIMIT match_count;
$$;

-- =============================================================================
-- Step 4: Backfill existing closed CAR and QDDR reports
-- =============================================================================
INSERT INTO public.car_case_repository (
  car_id, reference_no, details_of_nonconformance, root_cause_analysis,
  corrective_action, preventive_action, issue_category,
  requesting_department, responsible_department, product_material_name
)
SELECT
  id,
  reference_no,
  details_of_nonconformance,
  root_cause_analysis,
  COALESCE(corrective_action, 'No corrective action recorded'),
  preventive_action,
  CASE
    WHEN customer_complaint = true THEN 'customer_complaint'
    WHEN internal_audit = true THEN 'internal_audit'
    WHEN customer_audit_nonconformance = true THEN 'customer_audit'
    WHEN government_agency_audit = true THEN 'government_agency_audit'
    WHEN vendor_nonconformance = true THEN 'vendor_nonconformance'
    WHEN quality_food_safety = true THEN 'quality_food_safety'
    WHEN environment_health_safety = true THEN 'environment_health_safety'
    WHEN security_issue = true THEN 'security_issue'
    ELSE 'general'
  END,
  requesting_department,
  responsible_department,
  product_material_name
FROM public.car_reports
WHERE lower(coalesce(status, '')) = 'closed'
  AND details_of_nonconformance IS NOT NULL
  AND (corrective_action IS NOT NULL OR root_cause_analysis IS NOT NULL)
ON CONFLICT DO NOTHING;

INSERT INTO public.qddr_case_repository (
  qddr_id, reference_no, reason_of_discrepancy, material_description,
  corrective_action, preventive_action, disposal_approved
)
SELECT
  id,
  reference_no,
  reason_of_discrepancy,
  material_description,
  COALESCE(corrective_action, 'Approved for disposal'),
  preventive_action,
  true
FROM public.qddr_reports
WHERE lower(coalesce(status, '')) = 'closed'
  AND reason_of_discrepancy IS NOT NULL
ON CONFLICT DO NOTHING;

-- =============================================================================
-- Step 5: Update atomic reference generator function (Remove NCR)
-- =============================================================================
CREATE OR REPLACE FUNCTION public.next_report_reference(
  p_type text,
  p_year integer DEFAULT NULL
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_type text := upper(trim(coalesce(p_type, '')));
  v_next_seq integer;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('next_report_reference_' || v_type));

  IF v_type = 'CAR' THEN
    SELECT COALESCE(
      MAX(CAST(substring(reference_no FROM '^CAR-([0-9]+)$') AS integer)),
      0
    ) + 1
    INTO v_next_seq
    FROM public.car_reports
    WHERE reference_no ~ '^CAR-[0-9]+$';

    RETURN 'CAR-' || lpad(v_next_seq::text, 3, '0');

  ELSIF v_type = 'QDDR' THEN
    SELECT COALESCE(
      MAX(CAST(substring(reference_no FROM '^QDDR-([0-9]+)$') AS integer)),
      0
    ) + 1
    INTO v_next_seq
    FROM public.qddr_reports
    WHERE reference_no ~ '^QDDR-[0-9]+$';

    RETURN 'QDDR-' || lpad(v_next_seq::text, 3, '0');

  ELSE
    RAISE EXCEPTION 'Unsupported report type for reference generation: %. Only CAR and QDDR are supported.', p_type;
  END IF;
END;
$$;

